const state = {
  topic: null, level: 0, filter: "all", sound: true,
  answers: JSON.parse(localStorage.getItem("mindgrain-answers-v1") || "{}")
};

const $ = (selector, root = document) => root.querySelector(selector);
const $$ = (selector, root = document) => [...root.querySelectorAll(selector)];
const keyFor = (topic, level, index) => `${topic}-${level}-${index}`;

function save() { localStorage.setItem("mindgrain-answers-v1", JSON.stringify(state.answers)); }

function answeredCount(topicKey, level) {
  return topics[topicKey].levels[level].filter((_, i) => state.answers[keyFor(topicKey, level, i)] !== undefined).length;
}

function correctCount(topicKey, level) {
  return topics[topicKey].levels[level].filter((item, i) => state.answers[keyFor(topicKey, level, i)] === item.answer).length;
}

function renderTopics() {
  const items = ["defense", "emotions", "mbti", "enneagram"];
  $("#topicGrid").innerHTML = items.map((key, i) => {
    const topic = topics[key];
    const done = topic.levels.reduce((sum, _, level) => sum + answeredCount(key, level), 0);
    return `<button class="topic-card" type="button" data-start="${key}" aria-label="${topic.title} 테스트 시작">
      <img src="${topic.cover}" alt="" />
      <span class="topic-card-content">
        <span class="topic-index">0${i + 1}</span>
        <h3>${topic.title}</h3>
        <p>${topic.description}</p>
        <span class="topic-footer"><span>${done ? `${done}/30 진행` : "3 LEVEL · 30문항"}</span><span class="card-arrow">→</span></span>
      </span>
    </button>`;
  }).join("");
}

function openTopic(topicKey, level = 0) {
  state.topic = topicKey;
  state.level = Math.min(level, topics[topicKey].levels.length - 1);
  state.filter = "all";
  $("#homeView").classList.add("hidden");
  $("#quizView").classList.remove("hidden");
  renderQuiz();
  window.scrollTo({ top: 0, behavior: "smooth" });
  $("#main").focus({ preventScroll: true });
}

function goHome() {
  state.topic = null;
  $("#quizView").classList.add("hidden");
  $("#homeView").classList.remove("hidden");
  renderTopics();
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function renderQuiz() {
  const topic = topics[state.topic];
  const questions = topic.levels[state.level];
  $("#quizCover").src = topic.cover;
  $("#quizCover").alt = `${topic.title} 주제 표지`;
  $("#quizKicker").textContent = topic.kicker;
  $("#quizTitle").textContent = topic.title;
  $("#quizDescription").textContent = topic.description;
  document.documentElement.style.setProperty("--topic-accent", topic.accent);

  $("#levelTabs").innerHTML = topic.levels.length === 1
    ? `<button class="level-tab active" type="button" role="tab" aria-selected="true">20문항</button>`
    : topic.levels.map((_, i) => {
        const isDone = answeredCount(state.topic, i) === topic.levels[i].length;
        return `<button class="level-tab ${i === state.level ? "active" : ""}" type="button" role="tab" aria-selected="${i === state.level}" data-level="${i}">LV.${i + 1}${isDone ? ' <span class="done">✓</span>' : ""}</button>`;
      }).join("");

  const done = answeredCount(state.topic, state.level);
  const right = correctCount(state.topic, state.level);
  $("#sideProgressText").textContent = `${done} / ${questions.length}`;
  $("#sideProgressBar").style.width = `${done / questions.length * 100}%`;
  $("#quizStats").innerHTML = `응답 <strong>${done}</strong> · 정답 <strong>${right}</strong> · 총 ${questions.length}문항`;

  $$(".filter").forEach(btn => btn.classList.toggle("active", btn.dataset.filter === state.filter));
  const visible = questions.map((item, index) => ({ item, index })).filter(({ item, index }) => {
    const answer = state.answers[keyFor(state.topic, state.level, index)];
    if (state.filter === "unanswered") return answer === undefined;
    if (state.filter === "wrong") return answer !== undefined && answer !== item.answer;
    return true;
  });

  $("#questionList").innerHTML = visible.map(({ item, index }) => questionTemplate(item, index)).join("");
  $("#emptyState").classList.toggle("hidden", visible.length > 0);
  const complete = done === questions.length;
  $("#resultCard").classList.toggle("hidden", !complete || state.filter !== "all");
  if (complete) renderResult(right, questions.length);
}

function questionTemplate(item, index) {
  const selected = state.answers[keyFor(state.topic, state.level, index)];
  const answered = selected !== undefined;
  const letters = ["A", "B", "C", "D"];
  return `<article class="question-card ${answered ? "answered" : ""}" data-question="${index}">
    <div class="question-head"><span class="q-number">${String(index + 1).padStart(2, "0")}</span><h2>${item.prompt}</h2></div>
    <div class="options" role="group" aria-label="${index + 1}번 선택지">
      ${item.options.map((option, optionIndex) => {
        const isCorrect = answered && optionIndex === item.answer;
        const isWrong = answered && optionIndex === selected && selected !== item.answer;
        return `<button class="option ${isCorrect ? "correct" : ""} ${isWrong ? "wrong" : ""}" type="button" data-answer="${optionIndex}" ${answered ? "disabled" : ""}>
          <span class="option-letter">${letters[optionIndex]}</span><span>${option}</span>${isCorrect ? '<span class="option-mark">✓</span>' : isWrong ? '<span class="option-mark">×</span>' : ""}
        </button>`;
      }).join("")}
    </div>
    ${answered ? `<div class="explanation"><strong>${selected === item.answer ? "정답이에요." : `정답은 ${letters[item.answer]}예요.`}</strong> ${item.explanation}</div>` : ""}
  </article>`;
}

function renderResult(right, total) {
  const score = Math.round(right / total * 100);
  $("#resultScore").textContent = score;
  $("#resultMessage").textContent = score >= 90 ? "개념과 맥락을 매우 정확하게 이해하고 있어요." : score >= 70 ? "핵심을 잘 이해했어요. 오답 해설로 빈틈을 채워보세요." : score >= 50 ? "좋은 출발이에요. 헷갈린 개념을 차분히 복습해 보세요." : "정답보다 해설이 중요한 구간이에요. 한 문제씩 다시 살펴보세요.";
  const topic = topics[state.topic];
  const last = state.level === topic.levels.length - 1;
  $("#nextLevel").classList.toggle("hidden", last);
  $("#nextLevel").innerHTML = `다음 레벨 <span>→</span>`;
}

function chooseAnswer(card, optionIndex) {
  const questionIndex = Number(card.dataset.question);
  const key = keyFor(state.topic, state.level, questionIndex);
  if (state.answers[key] !== undefined) return;
  state.answers[key] = optionIndex;
  save();
  if (state.sound) playTone(optionIndex === topics[state.topic].levels[state.level][questionIndex].answer);
  renderQuiz();
  const updated = $(`[data-question="${questionIndex}"]`);
  if (updated) updated.scrollIntoView({ block: "nearest" });
}

function playTone(correct) {
  try {
    const AudioCtx = window.AudioContext || window.webkitAudioContext;
    const ctx = new AudioCtx();
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    osc.frequency.value = correct ? 660 : 260;
    gain.gain.setValueAtTime(.045, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(.001, ctx.currentTime + .16);
    osc.connect(gain).connect(ctx.destination); osc.start(); osc.stop(ctx.currentTime + .16);
  } catch (_) {}
}

function resetLevel() {
  const questions = topics[state.topic].levels[state.level];
  questions.forEach((_, i) => delete state.answers[keyFor(state.topic, state.level, i)]);
  save(); state.filter = "all"; renderQuiz(); showToast("이 레벨의 답안을 초기화했어요.");
}

function showProgress() {
  const rows = Object.entries(topics).map(([key, topic]) => {
    const total = topic.levels.flat().length;
    const done = topic.levels.reduce((sum, _, l) => sum + answeredCount(key, l), 0);
    const right = topic.levels.reduce((sum, _, l) => sum + correctCount(key, l), 0);
    return `<div class="progress-row"><div><h3>${topic.title}</h3><p>${done}/${total}문항 응답</p></div><strong>${done ? Math.round(right / done * 100) : 0}%</strong></div>`;
  }).join("");
  $("#progressContent").innerHTML = rows;
  if (!$("#progressDialog").open) $("#progressDialog").showModal();
}

let toastTimer;
function showToast(message) {
  const toast = $("#toast"); toast.textContent = message; toast.classList.add("show");
  clearTimeout(toastTimer); toastTimer = setTimeout(() => toast.classList.remove("show"), 2200);
}

document.addEventListener("click", event => {
  const start = event.target.closest("[data-start]");
  if (start) return openTopic(start.dataset.start);
  if (event.target.closest("[data-home]")) return goHome();
  const level = event.target.closest("[data-level]");
  if (level) { state.level = Number(level.dataset.level); state.filter = "all"; renderQuiz(); window.scrollTo({ top: 0, behavior: "smooth" }); return; }
  const filter = event.target.closest("[data-filter]");
  if (filter) { state.filter = filter.dataset.filter; renderQuiz(); return; }
  const option = event.target.closest(".option");
  if (option) return chooseAnswer(option.closest(".question-card"), Number(option.dataset.answer));
  if (event.target.closest("[data-close-dialog]")) $("#progressDialog").close();
});

